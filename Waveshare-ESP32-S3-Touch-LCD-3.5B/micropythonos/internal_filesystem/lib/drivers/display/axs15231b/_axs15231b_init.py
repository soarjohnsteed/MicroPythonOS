def init(self):
    param_buf = self._param_buf
    param_mv = self._param_mv

    # Exit sleep first, as panel_axs15231b_init() does.
    self.set_params(_AXS_LCD_SLPOUT)
    time.sleep_ms(100)  # NOQA

    # Memory data access control, right after sleep out.
    param_buf[0] = (
        self._madctl(
            self._color_byte_order,
            self._ORIENTATION_TABLE  # NOQA
        )
    )
    self.set_params(_AXS_LCD_MADCTL, param_mv[:1])

    # Interface pixel format: 0x55 for RGB565, 0x66 for RGB666.
    color_size = lv.color_format_get_size(self._color_space)
    if color_size == 2:
        pixel_format = 0x55
    else:
        pixel_format = 0x66

    param_buf[0] = pixel_format
    self.set_params(_AXS_LCD_IPF, param_mv[:1])

    # Panel brightness register (the actual backlight is a PWM GPIO).
    param_buf[0] = 0xD0
    self.set_params(_AXS_LCD_WRDISBV, param_mv[:1])

    # Panel specific register table.
    for cmd, data, delay in _VENDOR_INIT:
        n = len(data)
        if n:
            param_buf[:n] = bytes(data)
            self.set_params(cmd, param_mv[:n])
        else:
            self.set_params(cmd)
        if delay:
            time.sleep_ms(delay)  # NOQA

    # The C driver leaves DISPON to the application; the framework expects
    # the panel to be on after init().
    self.set_params(_AXS_LCD_DISPON)
    time.sleep_ms(120)  # NOQA
