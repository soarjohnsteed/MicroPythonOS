# AXS15231B initialization sequence for the Waveshare ESP32-S3-Touch-LCD-3.5B
#
# IMPORTANT: this panel does NOT take the generic Espressif/JC3248W535
# vendor sequence (vendor_specific_init_default[] in esp_lcd_axs15231b).
# Sending that sequence leaves the panel showing a garbled image.
# Waveshare ships a panel-specific table in the board's factory demo
# (ESP-IDF/01_factory/components/esp_bsp/bsp_display.c:lcd_init_cmds[]),
# which is byte for byte the same table Arduino_GFX uses for this panel
# (Arduino_AXS15231B.h:axs15231b_init_operations).  This file reproduces
# that table exactly.
#
# Command order follows panel_axs15231b_init() in the Espressif C driver:
#   SLPOUT (+100 ms) -> MADCTL -> COLMOD -> vendor table -> DISPON
# The vendor table itself ends with NORON, a second SLPOUT (+120 ms) and
# a RAMWR with 4 dummy bytes, just like the C table.

import time
from micropython import const  # NOQA

import lvgl as lv  # NOQA


_AXS_LCD_SLPOUT = const(0x11)  # Sleep out (C)
_AXS_LCD_NORON = const(0x13)  # Normal display mode on (C)
_AXS_LCD_DISPON = const(0x29)  # Display on (C)
_AXS_LCD_RAMWR = const(0x2C)  # Memory write (W)
_AXS_LCD_MADCTL = const(0x36)  # Memory data access control (W)
_AXS_LCD_IPF = const(0x3A)  # Interface pixel format (W)
_AXS_LCD_WRDISBV = const(0x51)  # Write display brightness value (W)


